    private static Guid Id(int number) => Guid.Parse($"81000000-0000-4000-8000-{number:000000000000}");

    public static async Task SeedAsync(AppDbContext database, CancellationToken token)
    {
        var bossId = DemoGameContent.BossId();
        var crisisId = DemoGameContent.CrisisId();
        var versions = await database.AssessmentVersions.AsNoTracking()
            .Where(version => (version.AssessmentId == bossId || version.AssessmentId == crisisId) && version.VersionNumber > 1)
            .Select(version => version.Id).ToListAsync(token);
        if (versions.Contains(Id(1)) && versions.Contains(Id(2))) return;
        if (versions.Count > 0)
            throw new InvalidOperationException("В первой теме уже есть другая версия испытаний. Проверь её перед загрузкой пилота.");

        var topic = await database.Topics.SingleAsync(item => item.Id == DemoData.TopicId, token);
        var lesson = await database.Lessons.SingleAsync(item => item.Id == DemoData.LessonId, token);
        topic.Title = TopicTitle;
        topic.Description = "Постоянный ток. Закон Ома, эквивалентное сопротивление и расчёт тока.";
        lesson.Title = TopicTitle;
        lesson.ContentMarkdown = Lecture;

        var publishedAt = DateTimeOffset.UtcNow;
        var boss = new AssessmentVersion
        {
            Id = Id(1), AssessmentId = bossId, VersionNumber = 2, PublishedAt = publishedAt,
            QuestionTimeLimitSeconds = 60, RequiredCorrectAnswers = 5, BossName = "Омнис",
            BossMaxHp = 100, DamagePerCorrectAnswer = 20, XpReward = 100, CoinsReward = 30
        };
        AddBossQuestions(boss);

        var crisis = new AssessmentVersion
        {
            Id = Id(2), AssessmentId = crisisId, VersionNumber = 2, PublishedAt = publishedAt,
            QuestionTimeLimitSeconds = 60, RequiredCorrectAnswers = 4, XpReward = 100, CoinsReward = 30
        };
        AddCrisisScenarios(crisis);
        database.AssessmentVersions.AddRange(boss, crisis);
        await database.SaveChangesAsync(token);
    }

