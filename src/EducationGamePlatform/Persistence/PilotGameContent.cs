    private static void AddScenario(AssessmentVersion version, int index, string title, string introduction, string illustration,
        (string Prompt, string Explanation, string[] Options)[] steps)
    {
        var scenario = new CrisisScenario
        {
            Id = Id(10 + index), AssessmentVersionId = version.Id, Title = title, SortOrder = index,
            Introduction = introduction + " Все действия относятся к виртуальному стенду. После старта есть 60 секунд.",
            IllustrationKey = illustration
        };
        version.Scenarios.Add(scenario);
        for (var i = 0; i < steps.Length; i++)
        {
            var position = index * 4 + i;
            var step = steps[i];
            AddQuestion(version, 200 + position, position, step.Prompt, step.Explanation, step.Options, scenario.Id);
        }
    }

    private static void AddQuestion(AssessmentVersion version, int id, int position, string prompt, string explanation,
        string[] options, Guid? scenarioId = null)
    {
        var question = new Question
        {
            Id = Id(id), AssessmentVersionId = version.Id, ScenarioId = scenarioId,
            SortOrder = position, Prompt = prompt, Explanation = explanation
        };
        question.Options = options.Select((option, index) => new AnswerOption
        {
            Id = Id(1000 + id * 4 + index), QuestionId = question.Id, Text = option,
            IsCorrect = index == 0, SortOrder = (position + index) % options.Length
        }).ToList();
        version.Questions.Add(question);
    }
